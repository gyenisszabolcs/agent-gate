    private static readonly FrozenDictionary<int, string> Special = Mappings.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries)
        .Select(item => item.Split(':')).ToFrozenDictionary(pair => int.Parse(pair[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture),
            pair => string.Concat(pair[1].Split(',').Select(hex => char.ConvertFromUtf32(int.Parse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture)))));

    public static string Fold(string value)
    {
        var result = new StringBuilder();
        foreach (var rune in value.EnumerateRunes())
            result.Append(Special.TryGetValue(rune.Value, out var mapped) ? mapped :
                rune.Value is >= 0x13A0 and <= 0x13F5 ? rune.ToString() : Rune.ToLowerInvariant(rune).ToString());
        return result.ToString();
    }
